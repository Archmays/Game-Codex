export function strokeStart(path: string): readonly [number, number] {
  const match = /^M(\d+) (\d+)/.exec(path);
  if (!match) throw new Error(`Stroke path needs a starting point: ${path}`);
  return [Number(match[1]), Number(match[2])];
}
